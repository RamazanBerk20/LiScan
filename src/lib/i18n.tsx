const supportedLocales = new Set<AppLocale>(
  languageOptions.map(({ value }) => value)
);

export function resolveLocale(
  preference: LanguagePreference,
  systemLanguages?: readonly string[]
): AppLocale {
  if (preference !== "system") return preference;
  const candidates =
    systemLanguages ??
    (typeof navigator === "undefined"
      ? ["en"]
      : navigator.languages.length > 0
        ? navigator.languages
        : [navigator.language]);
  for (const candidate of candidates) {
    const base = candidate.toLowerCase().split(/[-_]/)[0] as AppLocale;
    if (supportedLocales.has(base)) return base;
  }
  return "en";
}

function interpolate(template: string, values?: TranslationValues): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match
  );
}

export function translate(
  locale: AppLocale,
  key: MessageKey,
  values?: TranslationValues
): string {
  return interpolate(translations[locale][key], values);
}

export function issueLabel(
  issue: ScanIssue,
  t: (key: MessageKey, values?: TranslationValues) => string
): string {
  const keys: Record<ScanIssue["kind"], MessageKey> = {
    permission_denied: "issuePermissionDenied",
    io: "issueIo",
    excluded: "issueExcluded",
    filesystem_boundary: "issueFilesystemBoundary",
    changed: "issueChanged",
    unsupported: "issueUnsupported"
  };
  return t(keys[issue.kind]);
}

interface I18nContextValue {
  locale: AppLocale;
  t: (key: MessageKey, values?: TranslationValues) => string;
}

const defaultContext: I18nContextValue = {
  locale: "en",
  t: (key, values) => translate("en", key, values)
};

const I18nContext = createContext<I18nContextValue>(defaultContext);

export function I18nProvider({
  locale,
  children
}: {
  locale: AppLocale;
  children: ReactNode;
}) {
  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      t: (key, values) => translate(locale, key, values)
    }),
    [locale]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
